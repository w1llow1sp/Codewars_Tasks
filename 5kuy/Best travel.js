/**
 * Джон и Мэри хотят путешествовать между несколькими городами A, B, C ...
 * У Мэри на листе бумаги есть список расстояний между этими городами.
 * ls = [50, 55, 57, 58, 60].
 *
 * Джону надоело ехать, и он говорит Мэри, что не хочет проехать больше t = 174 миль и посетит только 3 города.
 *
 * Какие расстояния и, соответственно, какие города они выберут, чтобы сумма расстояний была как можно больше, чтобы угодить Мэри и Джону?
 *
 * Пример:
 * Имея список ls и 3 города, которые нужно посетить, они могут сделать выбор между:
 * [50,55,57],
 * [50,55,58],
 * [50,55,60],
 * [50,57,58],
 * [50,57,60],
 * [50,58,60],
 * [55,57,58],
 * [55,57,60],
 * [55,58,60],
 * [57,58,60].
 *
 * Суммы расстояний составляют: 162, 163, 165, 165, 167, 168, 170, 172, 173, 175.
 *
 * Тогда наибольшая возможная сумма с учетом ограничения 174 равна 173, а расстояния между 3 соответствующими городами - [55, 58, 60].
 *
 * Функция chooseBestSum (или choose_best_sum или ... в зависимости от языка)
 * принимает в качестве параметров
 *
 *  * t (максимальная сумма расстояний, целое число >= 0),
 *  * k (количество городов для посещения, k >= 1) и
 *  * ls (список расстояний, все расстояния - положительные или нулевые целые числа и в этом списке есть хотя бы один элемент).
 *
 *  Функция возвращает "наилучшую" сумму, то есть наибольшую возможную сумму k расстояний, меньшую или равную заданному пределу t,
 *  если такая сумма существует, или nil, null, None, Nothing, в зависимости от языка.
 *
 *  В этом случае с C, C++, D, Dart, Fortran, F#, Go, Julia, Kotlin, Nim, OCaml, Pascal, Perl, PowerShell, Reason, Rust, Scala, Shell, Swift возвращается -1.
 *
 * Примеры: ts = [50, 55, 56, 57, 58] choose_best_sum(163, 3, ts) -> 163 xs = [50] choose_best_sum(163, 3, xs) -> nil (или null или ... или -1 (C++, C, D, Rust, Swift, Go, ....) ys = [91, 74, 73, 85, 73, 81, 87] choose_best_sum(230, 3, ys) -> 228 Примечания: старайтесь не модифицировать входной список расстояний ls в некоторых языках этот "список" на самом деле является строкой (см. Примерные тесты).
 *
 */


function chooseBestSum(t, k, ls) {
    if (ls.length < k) return null;

    // Функция для генерации комбинаций
    function getCombinations(arr, k) {
        let result = [];

        function combine(start, current) {
            if (current.length === k) {
                result.push([...current]);
                return;
            }
            for (let i = start; i < arr.length; i++) {
                current.push(arr[i]);
                combine(i + 1, current);
                current.pop();
            }
        }

        combine(0, []);
        return result;
    }

    // Get all combitaions
    let combinations = getCombinations(ls, k);

    // Count all sum and filter
    let sums = combinations
        .map(combo => combo.reduce((sum, num) => sum + num, 0)) // Sum each combinarion
        .filter(sum => sum <= t) // Only sums <= t
        .sort((a, b) => b - a); // Sort

    // Return max sum or null , if  sum dont much
    return sums.length > 0 ? sums[0] : null;
}


ts = [91, 74, 73, 85, 73, 81, 87]
chooseBestSum(230, 3, ts)  // 163