/**
 * Задача о максимальной сумме подмассива состоит в нахождении максимальной
 * суммы непрерывной подпоследовательности в массиве или списке целых чисел:
 *
 * maxSequence([-2, 1, -3, 4, -1, 2, 1, -5, 4]) // должно быть 6: [4, -1, 2, 1]
 *
 * Простой случай - когда список состоит только из положительных чисел и максимальная сумма равна сумме всего массива.
 * Если список состоит только из отрицательных чисел, вместо этого возвращается 0.
 *
 * Считается, что пустой список имеет нулевую наибольшую сумму.
 * Обратите внимание, что пустой список или массив также является допустимым вложенным списком/подмассивом.
 */

export const maxSequence = (arr) => {
    // Проверяем пустой массив или массив из только отрицательных чисел
    if (arr.length === 0 || arr.every(el => el < 0)) {
        return 0;
    }

    // Алгоритм Кадане
    let maxSum = arr[0]; // Максимальная сумма подмассива
    let currentSum = arr[0]; // Текущая сумма подмассива

    for (let i = 1; i < arr.length; i++) {
        // Для каждого элемента решаем: начать новый подмассив или продолжить текущий
        currentSum = Math.max(arr[i], currentSum + arr[i]);
        // Обновляем максимальную сумму, если текущая больше
        maxSum = Math.max(maxSum, currentSum);
    }

    // Если максимальная сумма отрицательная, возвращаем 0
    return maxSum < 0 ? 0 : maxSum;
};