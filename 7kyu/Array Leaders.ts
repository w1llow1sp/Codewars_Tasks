/**
 Определение

 Элемент является лидером, если он больше суммы всех элементов
 справа от него.

 Задача

 Дан массив/список [] целых чисел, найдите всех лидеров в массиве.
 Примечания

 Размер массива/списка не менее 3.
 Числа в массиве/списке будут состоять из положительных,
 отрицательных и нулей

 Повторение чисел в массиве/списке может произойти.

 Возвращаемый массив/список должен хранить ведущие числа в том же
 порядке, что и исходный массив/список.
 Вход >> Выход Примеры arrayLeaders ({1, 2, 3, 4, 0}) ==> return {4} Пояснение: 4 больше суммы всех элементов справа от него Примечание: Последний элемент 0 равен правой сумме своих элементов (абстрактный ноль).

 arrayLeaders ({16, 17, 4, 3, 5, 2}) ==> return {17, 5, 2}

 Объяснение: 17 больше суммы всех элементов справа от него 5 больше суммы всех элементов справа от него Примечание : Последний элемент 2 больше суммы своих правых элементов (абстрактный ноль).

 arrayLeaders ({5, 2, -1}) ==> return {5, 2} Пояснение: 5 больше суммы всех элементов справа от него 2 больше суммы всех элементов справа от него Примечание : Последний элемент -1 меньше суммы его правых элементов (абстрактный ноль).

 arrayLeaders ({0, -1, -29, 3, 2}) ==> return {0, -1, 3, 2} Пояснение: 0 больше суммы всех элементов справа от него -1 больше суммы всех элементов справа от него 3 больше суммы всех элементов справа от него Примечание : Последний элемент 2 больше суммы своих правых элементов (абстрактный ноль).
 * @param numbers
 */

export function arrayLeaders(numbers: number[]): number[] {
    const leaders: number[] = [];
    let rightSum = 0;

    // Проходим массив с конца
    for (let i = numbers.length - 1; i >= 0; i--) {
        // Текущий элемент сравнивается с суммой элементов справа
        if (numbers[i] > rightSum) {
            leaders.unshift(numbers[i]); // Добавляем лидера в начало результата
        }
        // Обновляем сумму элементов справа
        rightSum += numbers[i];
    }

    return leaders;
}
